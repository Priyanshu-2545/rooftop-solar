// Generates FICTIONAL bill-like PNGs and the hash manifest. Run: npx tsx scripts/gen-samples.ts
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import sharp from "sharp";

type Bill = { file: string; name: string; consumer: string; units: string; load: string; blur?: number; smudge?: boolean };
const bills: Bill[] = [
  { file: "bill-good-340.png", name: "Sample Customer A", consumer: "410012345601", units: "340", load: "5.0" },
  { file: "bill-good-210.png", name: "Sample Customer B", consumer: "410012345602", units: "210", load: "3.0" },
  { file: "bill-good-85.png", name: "Sample Customer C", consumer: "410012345603", units: "85", load: "2.0" },
  { file: "bill-blurry.png", name: "Sample Customer D", consumer: "410012345604", units: "300", load: "4.0", blur: 14 },
  { file: "bill-ambiguous.png", name: "Sample Customer E", consumer: "41001234560?", units: "4?0", load: "?", smudge: true },
];

const svg = (b: Bill) => `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="1000">
<rect width="800" height="1000" fill="#fffdf8"/>
<rect x="30" y="30" width="740" height="940" fill="none" stroke="#1e2430" stroke-width="2"/>
<text x="60" y="100" font-family="Helvetica" font-size="34" font-weight="bold" fill="#1e2430">SAMPLE POWER DISTRIBUTION CO.</text>
<text x="60" y="140" font-family="Helvetica" font-size="20" fill="#5b6270">Electricity bill (fictional sample, not a real bill)</text>
<line x1="60" y1="165" x2="740" y2="165" stroke="#e3dccb" stroke-width="2"/>
<text x="60" y="230" font-family="Helvetica" font-size="24" fill="#1e2430">Consumer No: ${b.consumer}</text>
<text x="60" y="290" font-family="Helvetica" font-size="24" fill="#1e2430">Name: ${b.name}</text>
<text x="60" y="350" font-family="Helvetica" font-size="24" fill="#1e2430">Tariff: LT-I Residential</text>
<text x="60" y="410" font-family="Helvetica" font-size="24" fill="#1e2430">Sanctioned load: ${b.load} kW</text>
<text x="60" y="470" font-family="Helvetica" font-size="24" fill="#1e2430">Average units / month: ${b.units}</text>
${b.smudge ? '<rect x="40" y="200" width="720" height="300" fill="#bbb" opacity="0.35"/>' : ""}
</svg>`;

async function main() {
  mkdirSync("samples/bills", { recursive: true });
  const manifest: Record<string, string> = {};
  for (const b of bills) {
    let img = sharp(Buffer.from(svg(b))).png();
    if (b.blur) img = sharp(await img.toBuffer()).blur(b.blur).png();
    const buf = await img.toBuffer();
    writeFileSync(`samples/bills/${b.file}`, buf);
    manifest[createHash("sha256").update(buf).digest("hex")] = b.file;
  }
  writeFileSync(
    "lib/ai/sample-manifest.ts",
    `// GENERATED by scripts/gen-samples.ts. sha256 of sample bill -> file name.\nexport const SAMPLE_BILL_HASHES: Record<string, string> = ${JSON.stringify(manifest, null, 2)};\n`,
  );
  console.log("generated", Object.keys(manifest).length, "samples");
}
main().catch((e) => { console.error(e); process.exit(1); });
